#define SY_N 16u                 /* a syllable's phonemes with the last one's coda carried */
enum { SS_HOLD, SS_ON };         /* (sing_t.st, a plosive's: closure 0, burst 1, aspiration 2) */
typedef struct {
    uint8_t lang, lyr, gen, playing;   /* what it saw last: a change starts the lyric over */
    uint8_t pend, rst, gated, mono;    /* a note began; back to the start; a key held; the mono note */
    uint16_t loops;              /* the pattern's loops (LOOP) */
    int16_t posv;                /* POS as applied */
    uint8_t to, tl;              /* TEXT: the word's place and length in the text */
    uint8_t wsy, wns, mel;       /* the word's next syllable, its syllables; a "-" (hold the vowel) */
    uint8_t prem, tpl, tps, fem; /* GEN: syllables left in the phrase, the template, its place; a feminine noun */
    uint16_t phr;                /* GEN: the phrase */
    uint32_t rng;                /* GEN: the dice */
    uint16_t nsy;                /* syllables sung since the start */
    uint8_t ph[SY_N], np, nu, cd;   /* the syllable: [the last one's coda] onset, its nucleus, its coda */
    uint8_t i, st, cdon, fast;   /* the phoneme sounding, its stage; the coda asked (released); the carried coda's end */
    uint16_t tb;                 /* blocks left of the phoneme (0: held) */
    int16_t f[3], ff, fb, bm;    /* as it sounds: F1 F2 F3, the frication's resonance and bandwidth (Hz), bandwidths x/16 */
    int16_t gv, ga, gf;          /* voicing, aspiration, frication, Q15: the block's end .. */
    int16_t pv, pa, pf;          /* .. its start (formant_render ramps across) */
    uint8_t live;                /* the articulation has started (from rest: the formants at the first target) */
    char w[20];                  /* the word (shown; the generator's, read from here) */
} sing_t;
