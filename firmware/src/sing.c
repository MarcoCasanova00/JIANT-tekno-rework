/* ---------------------------------------------------------------------------------------------- phonemes --- */
enum { PC_SIL, PC_VOW, PC_GLI, PC_LIQ, PC_TAP, PC_TRL, PC_NAS, PC_PLO, PC_FRI, PC_ASP, PC_AFF };
/* the place of articulation (a sagittal head: the lips, the tongue's tip, blade, body, the velum, the glottis); bit 7
 * rounded lips */
enum { PL_NONE, PL_LAB, PL_LABDEN, PL_DEN, PL_ALV, PL_POST, PL_PAL, PL_VEL, PL_UVU, PL_GLO };
#define PL_RND 0x80u
typedef struct {
    uint16_t f1, f2, f3;         /* formant targets, Hz (adult male; SHIFT moves them); f1 0: the next vowel's (h) */
    uint8_t cls;                 /* PC_* */
    uint8_t av;                  /* voicing, /255 (a plosive's: its voice bar) */
    uint8_t af;                  /* frication (a plosive's: its burst; h: aspiration), /255 */
    uint8_t ff, fbw;             /* the frication's resonance and bandwidth, /50 Hz */
    uint8_t dur;                 /* ms: a consonant's steady part (a plosive's closure) */
    uint8_t bwm;                 /* the formants' bandwidths x /16 (nasals, laterals: wider) */
    uint8_t place;               /* PL_* | PL_RND */
} phon_t;
