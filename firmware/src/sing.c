/* VOICE words (JIANT 0.8.5): the VOICE engine sings syllables, words and lyrics (included by eng_formant.c).
 *
 * LANG (EDIT > WORDS, P_VLANG: OFF ES EN JA; OFF is VOICE as before, its vowels) turns a VOICE track into a singer: each
 * note it starts sings the next syllable of its lyric (a held note holds the vowel; a TIE holds it on; the release
 * sings the syllable's last consonants). The lyric (LYRIC, P_VLYR): TEXT, the track's own (typed on the device, sent
 * by the editor, saved with the project: lyr_txt), or W1..W16, words the dice puts together from the language's bank
 * (tools/lyrics/: themes LOVE NIGHT SEA SKY ROAD DREAM FIRE, or ANY), a phrase as long as the pattern's notes, or
 * S1..S8, scat (pseudo-words of the language's syllables). An empty TEXT sings W1.
 *
 * How the words are read, a syllable at a time (sy_word: the word's phonemes, a byte each, 0x40 the first of a
 * syllable): Spanish by rules (sy_es: the letters as Spanish reads them, seseo; sy_syl: the syllables, diphthongs and
 * the onset clusters pl br tr ..), Japanese as romaji (sy_ja: Hepburn and kunrei, a mora a syllable: "n" before a
 * consonant, a doubled consonant a longer closure, "-" the vowel again), English through the dictionary
 * (felucca_lyrics.h, ~2100 words from the CMU Pronouncing Dictionary, syllabified by tools/gen_lyrics.py) and rough
 * letter rules for a word it lacks. In the text: words are letters (case and apostrophes ignored, "_" joins two:
 * "mi_amor" is two syllables), "-" alone or between words holds the vowel one more note (a melisma), the rest
 * separates.
 *
 * How a syllable sounds (sing_block, once a block, 0.73 ms; formant_render reads it): its phonemes in turn, each a
 * target the formants F1..F3 glide to (one-pole, ~6 .. 23 ms), with the source's three gains: voicing (the glottal
 * pulse), aspiration (noise into the cascade: h, the aspiration after p t k) and frication (first-difference noise
 * into the fourth resonator, tuned to the consonant: s 5.8 kHz, sh 2.9 kHz, f 7 kHz, the bursts). Plosives: a closure
 * (silent, or a voice bar for b d g; the formants at the place's locus), a burst, the aspiration (EN ~45 ms, JA 20, ES
 * 6), the formants gliding to the vowel; affricates a closure into their fricative; nasals and liquids voiced with wide
 * bandwidths and less level; the Spanish tap a 22 ms dip, the trill three. The vowel holds while a key holds; at the
 * release the coda (an English diphthong's second vowel too) sounds, voiced ones held. A next note before the release
 * (LEGATO, or the next step) sings the coda quickly first.
 *
 * All per track (sing[]: ~100 bytes a track), none per voice: the voices of a track sing the same syllable (a choir).
 * The UI reads sing[] (sing_view): the word, the syllable count, the phoneme sounding, the formants, the gains: the
 * VOICE page shows them (and a later sagittal CT head can move with them). */
#include "felucca_lyrics.h"      /* generated by build.py (tools/gen_lyrics.py) */
