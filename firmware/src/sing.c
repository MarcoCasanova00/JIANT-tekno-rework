/* (0.9.8) the fricatives' noise band-passed (formant_word_render: 1 - z^-2 into F4, ~+5 dB at their peaks) and their gains
 * halved (sy_tick), then af set for softer, more natural sibilants: s z ~5 dB under 0.9.7's (s ~-16 .. -20 dB of the vowel, ~6
 * kHz), sh zh ~2 dB; f th v dh and the jota as before against s (f, th weak: ~5 dB under s) */
static int ph_vowel(uint32_t c) { return c < PH_COUNT && PHON[c].cls == PC_VOW; }
/* an affricate's fricative */
static uint32_t ph_fric(uint32_t c) { return c == PH_CH ? PH_SH : c == PH_TS ? PH_S : PH_ZH; }
static int ph_sonorant(uint32_t c)
{
    uint32_t k = c < PH_COUNT ? PHON[c].cls : PC_SIL;
    return k == PC_VOW || k == PC_GLI || k == PC_LIQ || k == PC_NAS;
}
#define SYB 0x40u                /* a phoneme byte: the first of a syllable */

/* ----------------------------------------------------------------------------------- reading the words --- */
#define SW_MAX 32u               /* a word's phonemes, at most */
enum { TK_C, TK_S, TK_W };       /* a token: a consonant, a strong vowel (a e o), a weak one (i u) */
static int sy_isv(int c) { return c == 'a' || c == 'e' || c == 'i' || c == 'o' || c == 'u'; }

/* Spanish letters -> tokens (tools/gen_lyrics.py es_tokens: the same) */
static uint32_t sy_es_tok(const char *w, uint32_t n, uint8_t *tc, uint8_t *tk)
{
    uint32_t i, m = 0;
    for (i = 0; i < n && m + 2u <= SW_MAX; i++) {
        int c = w[i], nx = i + 1u < n ? w[i + 1u] : 0, nx2 = i + 2u < n ? w[i + 2u] : 0;
        uint32_t code = 0xFFu, kind = TK_C;
        switch (c) {
        case 'a': code = PH_A; kind = TK_S; break;
        case 'e': code = PH_E; kind = TK_S; break;
        case 'o': code = PH_O; kind = TK_S; break;
        case 'i': code = PH_I; kind = TK_W; break;
        case 'u': code = PH_U; kind = TK_W; break;
        case 'y':
            if (sy_isv(nx)) code = PH_Y;
            else { code = PH_I; kind = TK_W; }
            break;
        case 'c':
            if (nx == 'h') { code = PH_CH; i++; }
            else code = nx == 'e' || nx == 'i' ? PH_S : PH_K;
            break;
        case 'q': code = PH_K; if (nx == 'u') i++; break;
        case 'g':
            if (nx == 'e' || nx == 'i') code = PH_X;
            else { code = PH_G; if (nx == 'u' && (nx2 == 'e' || nx2 == 'i')) i++; }
            break;
        case 'j': code = PH_X; break;
        case 'x': tc[m] = PH_K; tk[m++] = TK_C; code = PH_S; break;
        case 'z': case 's': code = PH_S; break;
        case 'v': case 'b': code = PH_B; break;
        case 'd': code = PH_D; break;
        case 'f': code = PH_F; break;
        case 'k': code = PH_K; break;
        case 'p': code = PH_P; break;
        case 't': code = PH_T; break;
        case 'm': code = PH_M; break;
        case 'w': code = PH_W; break;
        case 'l':
            if (nx == 'l') { code = PH_Y; i++; }
            else code = PH_L;
            break;
        case 'n':
            if (nx == 'y' && sy_isv(nx2)) { code = PH_NY; i++; }
            else code = PH_N;
            break;
        case 'r':
            if (nx == 'r') { code = PH_RR; i++; }
            else code = !m || tc[m - 1u] == PH_N || tc[m - 1u] == PH_L || tc[m - 1u] == PH_S ? PH_RR : PH_RT;
            break;
        default: break;                                  /* h, the rest: silent */
        }
        if (code != 0xFFu) {
            tc[m] = (uint8_t)code;
            tk[m++] = (uint8_t)kind;
        }
    }
    return m;
}
static int sy_es_cl(uint32_t a, uint32_t b)              /* an onset cluster: p b f k g t d + l r (not dl) */
{
    return (a == PH_P || a == PH_B || a == PH_F || a == PH_K || a == PH_G || a == PH_T || a == PH_D) &&
           (b == PH_L || b == PH_RT) && !(a == PH_D && b == PH_L);
}
/* tokens -> the word's phonemes with their syllables (gen_lyrics.py syllabify): the vowel groups (split between two
 * strong vowels) are the syllables; a group's nucleus its first strong vowel, else its last; the weak ones before it
 * glides (y w), after it offglides; between two groups one consonant goes to the next, two too when a cluster, else
 * they split (more: the last two or one to the next). Returns the phonemes, *ns the syllables (0: no vowel) */
static uint32_t sy_syl(uint8_t *tc, const uint8_t *tk, uint32_t m, uint8_t *out, uint32_t *ns)
{
    uint8_t st[SW_MAX];
    uint32_t i = 0, g = 0, pa = 0, k;
    for (k = 0; k < m; k++)
        st[k] = 0;
    while (i < m) {
        uint32_t j, nu;
        if (tk[i] == TK_C) {
            i++;
            continue;
        }
        for (j = i + 1u; j < m && tk[j] != TK_C && !(tk[j] == TK_S && tk[j - 1u] == TK_S); j++)
            ;
        for (nu = i; nu < j && tk[nu] != TK_S; nu++)
            ;
        if (nu == j)
            nu = j - 1u;
        for (k = i; k < nu; k++)
            tc[k] = tc[k] == PH_I ? PH_Y : PH_W;
        if (g) {
            uint32_t c = i - pa;
            if (!c) st[i] = 1;
            else if (c == 1u) st[pa] = 1;
            else if (c == 2u) st[sy_es_cl(tc[pa], tc[pa + 1u]) ? pa : pa + 1u] = 1;
            else st[sy_es_cl(tc[i - 2u], tc[i - 1u]) ? i - 2u : i - 1u] = 1;
        }
        g++;
        pa = j;
        i = j;
    }
    *ns = g;
    if (!g)
        return 0;
    st[0] = 1;
    for (k = 0; k < m; k++)
        out[k] = (uint8_t)(tc[k] | (st[k] ? SYB : 0u));
    return m;
}

/* Japanese romaji -> morae (gen_lyrics.py ja_nmora counts the same) */
static uint32_t sy_ja(const char *w, uint32_t n, uint8_t *out, uint32_t *ns)
{
    uint32_t i = 0, m = 0, k = 0, gem = 0, lastv = PH_A;
    static const uint8_t JV[5] = {PH_A, PH_I, PH_UJ, PH_E, PH_O};   /* a i u e o */
#define JA_V(c) ((c) == 'a' ? 0 : (c) == 'i' ? 1 : (c) == 'u' ? 2 : (c) == 'e' ? 3 : (c) == 'o' ? 4 : -1)
#define JA_PUT(c, s) do { if (m < SW_MAX) out[m++] = (uint8_t)((c) | ((s) ? SYB : 0u)); } while (0)
    while (i < n) {
        int c = w[i], nx = i + 1u < n ? w[i + 1u] : 0, nx2 = i + 2u < n ? w[i + 2u] : 0;
        if (JA_V(c) >= 0) {                                /* a vowel */
            if (gem) JA_PUT(PH_SIL, 1);
            lastv = c == 'u' && lastv == PH_O && k ? PH_O : JV[JA_V(c)];   /* (ou: a long o, sung o-o) */
            JA_PUT(lastv, !gem);
            gem = 0;
            k++;
            i++;
        } else if (c == '-') {                             /* the vowel again */
            JA_PUT(lastv, 1);
            k++;
            i++;
        } else if (c == 'n' && JA_V(nx) < 0 && nx != 'y') {   /* the moraic n */
            JA_PUT(PH_NM, 1);
            k++;
            i += (nx == 'n' || nx == '\'') && JA_V(nx2) < 0 ? 2u : 1u;
        } else if ((c == nx && c >= 'a' && c <= 'z') || (c == 't' && nx == 'c')) {   /* a doubled consonant */
            gem = 1;
            i++;
        } else if (c < 'a' || c > 'z') {                   /* (an apostrophe, ..) */
            i++;
        } else {                                           /* a consonant (+ y) + a vowel */
            uint32_t j = i, on = 0xFFu, pal = 0, v;
            int vv;
            switch (c) {
            case 's': on = nx == 'h' ? PH_SH : PH_S; break;
            case 'c': on = nx == 'h' ? PH_CH : PH_K; break;
            case 't': on = nx == 's' ? PH_TS : PH_T; break;
            case 'k': on = PH_K; break;
            case 'n': on = PH_N; break;
            case 'h': on = PH_H; break;
            case 'f': on = PH_F; break;
            case 'm': on = PH_M; break;
            case 'y': on = PH_Y; break;
            case 'r': case 'l': on = PH_RT; break;
            case 'w': on = PH_W; break;
            case 'g': on = PH_G; break;
            case 'z': on = PH_Z; break;
            case 'j': on = PH_J; break;
            case 'd': on = PH_D; break;
            case 'b': on = PH_B; break;
            case 'p': on = PH_P; break;
            case 'v': on = PH_V; break;
            default: on = PH_K; break;
            }
            while (j < n && JA_V(w[j]) < 0 && w[j] != '-') {
                if (j > i && w[j] == 'y')
                    pal = 1;
                j++;
            }
            vv = j < n ? JA_V(w[j]) : -1;
            v = vv >= 0 ? JV[vv] : PH_UJ;                  /* (a consonant alone: sung with u) */
            if (on == PH_S && vv == 1) on = PH_SH;         /* si -> shi, ti -> chi, tu -> tsu, hu -> fu, zi di -> ji, */
            else if (on == PH_T && vv == 1) on = PH_CH;    /* du -> zu */
            else if (on == PH_T && vv == 2) on = PH_TS;
            else if (on == PH_H && vv == 2) on = PH_F;
            else if ((on == PH_Z || on == PH_D) && vv == 1) on = PH_J;
            else if (on == PH_D && vv == 2) on = PH_Z;
            if (on == PH_SH || on == PH_CH || on == PH_J)
                pal = 0;                                   /* (sha cha ja: palatal already) */
            {
                uint8_t mo[4];
                uint32_t nm = 0, q;
                if (gem) mo[nm++] = PH_SIL;
                if (!(on == PH_W && vv == 4))              /* (wo: o) */
                    mo[nm++] = (uint8_t)on;
                if (pal) mo[nm++] = PH_Y;
                mo[nm++] = (uint8_t)(lastv = v);
                for (q = 0; q < nm; q++)
                    JA_PUT(mo[q], !q);
            }
            gem = 0;
            k++;
            i = vv >= 0 ? j + 1u : j;
        }
    }
#undef JA_V
#undef JA_PUT
    *ns = k;
    return m;
}

/* English: the dictionary (tools/gen_lyrics.py en_dict_pack; 0.9.0: Huffman-coded, 4.4 KB less than as bytes): a word
 * is the count of letters shared with the word before (code P), the rest of its letters (code L: 0 .. 25 a .. z) and
 * LY_END, its phonemes (code H: SYB | code) and LY_END; each LY_EN_BLK-th word whole, from a byte, LY_EN_IDX its place.
 * A code: hc the codes of each length 1 .. 15, then the symbols in code order (canonical); lut the next k bits ->
 * length << 8 | symbol (0: a longer code, read from hc). The reader keeps the next n bits in acc (MSB first), at least
 * 25 after each symbol (a code is at most 15), reading up to 4 bytes ahead (the dictionary ends with 4 to spare) */
typedef struct { const uint8_t *hc; const uint16_t *lut; uint32_t k; } ly_code_t;
static const ly_code_t LY_CP = {LY_EN_HCP, LY_EN_LUTP, LY_EN_KP}, LY_CL = {LY_EN_HCL, LY_EN_LUTL, LY_EN_KL},
                       LY_CH = {LY_EN_HCH, LY_EN_LUTH, LY_EN_KH};
typedef struct { const uint8_t *p; uint32_t acc, n; } ly_rd_t;
static inline __attribute__((always_inline)) void ly_fill(ly_rd_t *r)
{
    while (r->n <= 24u) {
        r->acc |= (uint32_t)*r->p++ << (24u - r->n);
        r->n += 8u;
    }
}
static void ly_at(ly_rd_t *r, uint32_t blk)              /* at block blk's first word */
{
    r->p = &LY_EN_DICT[LY_EN_IDX[blk]];
    r->acc = r->n = 0;
    ly_fill(r);
}
static __attribute__((noinline)) uint32_t ly_sym(ly_rd_t *r, const ly_code_t *c)
{
    uint32_t e = c->lut[r->acc >> (32u - c->k)];
    if (!e) {                                            /* a code longer than k bits */
        uint32_t first = 0, idx = 0, n;
        for (n = 1; n < 15u; n++) {
            uint32_t code = r->acc >> (32u - n), cnt = c->hc[n - 1u];
            if (code - first < cnt)
                break;
            idx += cnt;
            first = (first + cnt) << 1;
        }
        e = n << 8 | c->hc[15u + idx + (r->acc >> (32u - n)) - first];
    }
    r->acc <<= e >> 8;
    r->n -= e >> 8;
    ly_fill(r);
    return e & 255u;
}
/* key's phonemes (SYB | code) into out (SW_MAX; the rest dropped): how many, 0 = not there */
static uint32_t sy_en_find(const char *key, uint32_t kn, uint8_t *out)
{
    uint32_t lo = 0, hi = (uint32_t)NELEM(LY_EN_IDX), n;
    ly_rd_t r;
    char w[24];
    if (kn && key[0] >= 'a' && key[0] <= 'z') {          /* the blocks from the one before the key's letter's first */
        lo = LY_EN_LET[key[0] - 'a'];
        hi = LY_EN_LET[key[0] - 'a' + 1];
        lo -= lo > 0u;
    }
    while (hi - lo > 1u) {                               /* the last block whose first word is <= the key */
        uint32_t mid = (lo + hi) / 2u, i = 0, s;
        int c = 0;
        ly_at(&r, mid);
        (void)ly_sym(&r, &LY_CP);                        /* (0: a block's first word is whole) */
        while (!c) {
            int a = i < kn ? key[i] : 0, b;
            s = ly_sym(&r, &LY_CL);
            b = s == LY_END ? 0 : 'a' + (int)s;
            c = a - b;
            if (!a || !b)
                break;
            i++;
        }
        if (c >= 0) lo = mid;
        else hi = mid;
    }
    ly_at(&r, lo);
    for (n = 0; n < LY_EN_BLK && lo * LY_EN_BLK + n < LY_EN_N; n++) {
        uint32_t wl = ly_sym(&r, &LY_CP), s, m = 0;
        while ((s = ly_sym(&r, &LY_CL)) != LY_END) {
            if (wl < sizeof w) w[wl] = (char)('a' + s);
            wl++;
        }
        if (wl == kn && wl <= sizeof w) {
            uint32_t i;
            for (i = 0; i < kn && w[i] == key[i]; i++)
                ;
            if (i == kn) {
                while ((s = ly_sym(&r, &LY_CH)) != LY_END)
                    if (m < SW_MAX) out[m++] = (uint8_t)s;
                return m;
            }
        }
        while (ly_sym(&r, &LY_CH) != LY_END)             /* (the phonemes of a word that is not it) */
            ;
    }
    return 0;
}
/* a word the dictionary lacks: rough letter rules, then the syllables as Spanish's (vowel groups) */
static uint32_t sy_en_rules(const char *w, uint32_t n, uint8_t *tc, uint8_t *tk)
{
    uint32_t i, m = 0, magic = 0xFFu;
#define EN_T(c, k) do { if (m < SW_MAX) { tc[m] = (uint8_t)(c); tk[m++] = (uint8_t)(k); } } while (0)
    if (n >= 3u && w[n - 1u] == 'e' && !sy_isv(w[n - 2u]) && sy_isv(w[n - 3u]))
        magic = n - 3u;                                  /* a silent e: the vowel before says its name */
    for (i = 0; i < n; i++) {
        int c = w[i], nx = i + 1u < n ? w[i + 1u] : 0, nx2 = i + 2u < n ? w[i + 2u] : 0;
        if (i == n - 1u && c == 'e' && n > 2u) break;    /* (a final e: silent) */
        if (sy_isv(c) || c == 'y') {
            if (c == 'y' && (i == 0u || sy_isv(nx))) { EN_T(PH_Y, TK_C); continue; }
            if (c == 'y') { EN_T(i == n - 1u ? PH_I : PH_IH, TK_S); continue; }
            if (i == magic) {
                if (c == 'a') { EN_T(PH_E, TK_S); EN_T(PH_IH, TK_W); }
                else if (c == 'i') { EN_T(PH_AA, TK_S); EN_T(PH_IH, TK_W); }
                else if (c == 'o') { EN_T(PH_O, TK_S); EN_T(PH_UH, TK_W); }
                else if (c == 'u') EN_T(PH_U, TK_S);
                else EN_T(PH_I, TK_S);
                continue;
            }
            if ((c == 'e' && (nx == 'e' || nx == 'a')) ) { EN_T(PH_I, TK_S); i++; continue; }
            if (c == 'o' && nx == 'o') { EN_T(PH_U, TK_S); i++; continue; }
            if (c == 'o' && (nx == 'u' || nx == 'w')) { EN_T(PH_AA, TK_S); EN_T(PH_UH, TK_W); i++; continue; }
            if (c == 'a' && (nx == 'i' || nx == 'y')) { EN_T(PH_E, TK_S); EN_T(PH_IH, TK_W); i++; continue; }
            if (c == 'o' && nx == 'a') { EN_T(PH_O, TK_S); EN_T(PH_UH, TK_W); i++; continue; }
            if (c == 'o' && (nx == 'i' || nx == 'y')) { EN_T(PH_AO, TK_S); EN_T(PH_IH, TK_W); i++; continue; }
            if (c == 'a' && (nx == 'u' || nx == 'w')) { EN_T(PH_AO, TK_S); i++; continue; }
            if (c == 'i' && nx == 'g' && nx2 == 'h') { EN_T(PH_AA, TK_S); EN_T(PH_IH, TK_W); i += 2u; continue; }
            EN_T(c == 'a' ? PH_AE : c == 'e' ? PH_EH : c == 'i' ? PH_IH : c == 'o' ? PH_AA : PH_AH, TK_S);
            continue;
        }
        if (c == 't' && nx == 'h') { EN_T(PH_TH, TK_C); i++; continue; }
        if (c == 's' && nx == 'h') { EN_T(PH_SH, TK_C); i++; continue; }
        if (c == 'c' && nx == 'h') { EN_T(PH_CH, TK_C); i++; continue; }
        if (c == 'p' && nx == 'h') { EN_T(PH_F, TK_C); i++; continue; }
        if (c == 'w' && nx == 'h') { EN_T(PH_W, TK_C); i++; continue; }
        if (c == 'c' && nx == 'k') { EN_T(PH_K, TK_C); i++; continue; }
        if (c == 'q' && nx == 'u') { EN_T(PH_K, TK_C); EN_T(PH_W, TK_C); i++; continue; }
        if (c == 'k' && nx == 'n' && !i) continue;
        if (c == 'w' && nx == 'r') continue;
        if (c == 'g' && nx == 'h') { i++; continue; }
        if (c == 'n' && nx == 'g' && !sy_isv(nx2)) { EN_T(PH_NG, TK_C); i++; continue; }
        switch (c) {
        case 'b': EN_T(PH_B, TK_C); break;
        case 'c': EN_T(nx == 'e' || nx == 'i' || nx == 'y' ? PH_S : PH_K, TK_C); break;
        case 'd': EN_T(PH_D, TK_C); break;
        case 'f': EN_T(PH_F, TK_C); break;
        case 'g': EN_T(PH_G, TK_C); break;
        case 'h': if (sy_isv(nx)) EN_T(PH_H, TK_C); break;
        case 'j': EN_T(PH_J, TK_C); break;
        case 'k': EN_T(PH_K, TK_C); break;
        case 'l': if (nx != 'l') EN_T(PH_L, TK_C); break;
        case 'm': EN_T(PH_M, TK_C); break;
        case 'n': EN_T(PH_N, TK_C); break;
        case 'p': EN_T(PH_P, TK_C); break;
        case 'r': EN_T(PH_RA, TK_C); break;
        case 's': EN_T(i && sy_isv(w[i - 1u]) && sy_isv(nx) ? PH_Z : PH_S, TK_C); break;
        case 't': EN_T(PH_T, TK_C); break;
        case 'v': EN_T(PH_V, TK_C); break;
        case 'w': EN_T(PH_W, TK_C); break;
        case 'x': EN_T(PH_K, TK_C); EN_T(PH_S, TK_C); break;
        case 'z': EN_T(PH_Z, TK_C); break;
        default: break;
        }
    }
#undef EN_T
    return m;
}

/* word w (lower case letters, n) in lang -> out (SW_MAX), its phonemes; *ns its syllables (0: none, a word to skip) */
static uint32_t sy_word(uint32_t lang, const char *w, uint32_t n, uint8_t *out, uint32_t *ns)
{
    uint8_t tc[SW_MAX], tk[SW_MAX];
    uint32_t m;
    *ns = 0;
    if (!n)
        return 0;
    if (lang == LG_JA)
        return sy_ja(w, n, out, ns);
    if (lang == LG_EN) {
        uint32_t len = sy_en_find(w, n, out), i;
        if (len) {
            for (i = 0; i < len; i++)
                *ns += (out[i] & SYB) != 0u;
            return len;
        }
        m = sy_en_rules(w, n, tc, tk);
    } else {
        m = sy_es_tok(w, n, tc, tk);
    }
    return sy_syl(tc, tk, m, out, ns);
}

